"""Migrations: the Alembic history applies cleanly on an empty database (AC-00-05)."""

from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, text

pytestmark = pytest.mark.integration

PROJECT_ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture
def empty_test_database(test_database_url: str) -> Iterator[str]:
    """Reset the public schema of the test database so it starts empty."""
    engine = create_engine(test_database_url)
    with engine.begin() as connection:
        connection.execute(text("DROP SCHEMA public CASCADE"))
        connection.execute(text("CREATE SCHEMA public"))
    engine.dispose()
    yield test_database_url


def _alembic_config(database_url: str) -> Config:
    """Build an Alembic config for the project pointed at the given database."""
    config = Config(str(PROJECT_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(PROJECT_ROOT / "migrations"))
    config.set_main_option("sqlalchemy.url", database_url)
    return config


def test_ac00_05_migrations_apply_on_empty_database(empty_test_database: str) -> None:
    config = _alembic_config(empty_test_database)

    command.upgrade(config, "head")

    # Raises AutogenerateDiffsDetected if SQLModel.metadata and the schema differ.
    command.check(config)


def test_ac01_09_identity_migrations_clean(empty_test_database: str) -> None:
    config = _alembic_config(empty_test_database)

    command.upgrade(config, "head")
    command.check(config)
